'use strict';
const fs=require('fs'),path=require('path'),crypto=require('crypto'),assert=require('assert').strict,vm=require('vm');
const root=path.resolve(__dirname,'../..');
const manifest=require(path.join(root,'rindelab/data/carimages-rights-import-20261122.json'));
const coverage=require(path.join(root,'rindelab/data/catalog-coverage-20261122.json'));
assert(manifest.provider.includes('CarImages Rights'));
assert(manifest.dataset.startsWith('https://carimages.org/'));
assert.equal(manifest.photos.length,manifest.stats.downloaded);
assert.equal(manifest.stats.missingBefore,407);
assert.equal(coverage.summary.photosInLibrary,292+manifest.photos.length);
assert(coverage.summary.withoutFamilyPhoto<=407);
const unique=new Set();
const context={window:{},document:{addEventListener(){}},HTMLImageElement:class{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'rindelab/v2-photos.js'),'utf8'),context);
const photos=context.window.RindelabPhotos;
assert.equal(photos.count,292+manifest.photos.length);
for(const p of manifest.photos){
 assert(p.author&&p.model&&p.brand&&p.family&&p.pattern);
 assert(p.origin==='carimages-rights'||p.origin==='wikidata-p18');
 assert(p.source.startsWith('https://commons.wikimedia.org/wiki/File:'));
 assert(p.licenseUrl.startsWith('https://creativecommons.org/'));
 assert(/^CC0|^CC BY(?:-SA)? [234]\.0(?: [a-z]{2})?$|^Public domain$/i.test(p.license));
 assert(!unique.has(p.localSrc));unique.add(p.localSrc);
 const b=fs.readFileSync(path.join(root,'rindelab',p.localSrc));
 assert.equal(b.length,p.bytes);
 assert(b.length>=12000&&b.length<=1000000);
 assert.equal(b[0],255);assert.equal(b[1],216);
 assert.equal(b.at(-2),255);assert.equal(b.at(-1),217);
 assert.equal(crypto.createHash('sha256').update(b).digest('hex'),p.sha256);
 const found=photos.findCommercial({brand:p.brand,family:p.family,checkedAt:'2026-11-22'});
 assert(found,'Photo association failed: '+p.brand+' '+p.model);
}
console.log('PASS CarImages Rights importer:',manifest.photos.length,'licenced JPEG photos; total',photos.count,'remaining commercial',coverage.summary.withoutFamilyPhoto);
