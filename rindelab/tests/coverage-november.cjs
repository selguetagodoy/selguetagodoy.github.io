'use strict';
const assert=require('node:assert/strict');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const rd=p=>require(path.join(root,p));
const manifest=rd('vehiculos/data/manifest.json');
const legacy=manifest.files.flatMap(p=>rd('vehiculos/'+p)).filter(x=>x&&x[0]&&x[1]&&x[8]&&x[8]<=manifest.published);
const api=rd('rindelab/sii/official-api-mapper.js');
const october=api.load([1,2,3,4].map(i=>rd('rindelab/data/oficial-api-20261018-'+String(i).padStart(2,'0')+'.json')),legacy);
const november=rd('rindelab/data/oficial-api-20261122.json');
const latest=api.loadIncremental(november,legacy,october);
const combined=[...legacy,...october,...latest];
const prices=rd('rindelab/sii/commercial-2026.json');
const coverage=rd('rindelab/sii/coverage-matcher.js');
const report=coverage.analyze(prices,combined,november.retrieved);
assert.equal(new Set(combined.map(r=>r[9])).size,8394);
assert.equal(report.threeCvRecords,8394);
assert.equal(report.commercialPrices,1514);
assert.equal(report.commercialFamilies,720);
assert.equal(report.matchedFamilies,488);
assert.equal(report.unmatchedFamilies,232);
assert.equal(report.matchedFamilies+report.unmatchedFamilies,report.commercialFamilies);
assert(report.rows.every(r=>r.sourceUrls.every(u=>/^https:\/\//.test(u))));
assert.equal(report.published,'2026-11-22');
const may=coverage.analyze(prices,legacy,manifest.published);
assert.equal(may.threeCvRecords,8053);
assert.equal(report.matchedFamilies-may.matchedFamilies,9);
console.log('PASS Cobertura 3CV 22/11: 8.394 códigos, 488 familias con candidatos, 232 sin coincidencia; 1.514 referencias comerciales.');
