'use strict';
const assert=require('node:assert/strict'),C=require('../sii/catalog-identity.js');
const source=require('../data/market-price-unresolved-20261022.json');
const latest=require('../data/market-price-fifthpass-20261022.json');
const backlog=require('../data/market-price-unresolved-after-fifthpass-20261022.json');
assert.equal(source.remainingCases,227);
assert.equal(latest.schemaVersion,1);
assert.equal(latest.baselinePending,227);
assert.equal(latest.newFamilyReferences,21);
assert.equal(latest.pendingAfter,206);
assert.equal(latest.withFamilyReferences,366);
assert.equal(latest.records.length,21);
assert.equal(backlog.records.length,206);
assert.equal(backlog.withFamilyReferences,366);
assert.equal(backlog.categoryCounts['unmatched-catalog'],189);
assert.equal(backlog.categoryCounts['expired-price-reference'],14);
assert.equal(backlog.categoryCounts['other-powertrain'],3);
const key=r=>C.norm(r.model)+'|'+r.homologationDate+'|'+r.homologationCodeSuffix;
const prev=new Map(source.records.map(r=>[key(r),r])),seen=new Set();
for(const r of latest.records){
 const id=key(r);assert(!seen.has(id),'Duplicated homologation '+id);seen.add(id);
 assert(prev.has(id),'Missing original 3CV '+id);
 assert.equal(r.priceAssignedTo3CV,false);
 assert.equal(r.classification,'commercial-family-price-reference-only');
 assert.equal(r.priorCategory,prev.get(id).category);
 assert.match(r.reference.sourceUrl,/^https:\/\//);
 assert(r.reference.commercialVersion);
 assert(r.reference.notes);
 assert(Number.isSafeInteger(r.reference.priceListClp)&&r.reference.priceListClp>0);
}
const byName=name=>latest.records.filter(r=>C.norm(r.model)===C.norm(name));
assert.equal(byName('Maxus T70 4x2 6MT')[0].reference.priceListClp,19990000);
assert.equal(byName('Maxus T70 4x4 8AT')[0].reference.priceListClp,24990000);
assert.equal(byName('Gac GS4 MAX 1.5T AT GB')[0].reference.matchedLevel,'familia-motor-caja-acabado-solo-GL');
assert.equal(byName('Gac Aion UT EV AT 2WD (44 Kwh)')[0].reference.priceListClp,20990000);
assert(!byName('Gac Aion UT EV AT 2WD (60 Kwh)').length,'No aplicar precio de 44kWh a 60kWh');
assert.equal(byName('Audi New A5 quattro')[0].reference.validUntil,'2026-09-30');
assert.equal(byName('KYC Gran Mamut X5 Plus DC')[0].reference.priceKind,'listado-portal-sin-vigencia');
assert.equal(byName('Citroen Aircross 1.3 MT Shine')[0].reference.priceListClp,16790000);
assert.equal([...seen,...backlog.records.map(key)].length,227);
assert.equal(new Set([...seen,...backlog.records.map(key)]).size,227);
console.log('PASS quinto cruce: 21 referencias comerciales diferenciadas, 366 con referencia y 206 pendientes; Audi histórico, GAC GL no GB, AION 44 distinto 60');
