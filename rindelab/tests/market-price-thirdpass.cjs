'use strict';
const assert=require('node:assert/strict');
const C=require('../sii/catalog-identity.js');
const baseline=require('../data/price-association-audit-20261022.json');
const followup=require('../data/market-price-followup-20261022.json');
const third=require('../data/market-price-thirdpass-20261022.json');
assert.equal(baseline.records.length,572);
assert.equal(third.schemaVersion,1);
assert.equal(third.summary.baselinePending,274);
assert.equal(third.summary.additionalFamilyReference,37);
assert.equal(third.summary.newFamilyReview,335);
assert.equal(third.summary.stillPending,237);
assert.equal(third.records.length,37);
assert.equal(third.historical.length,7);
const id=r=>C.norm(r.model)+'|'+r.homologationDate+'|'+r.homologationCodeSuffix;
const base=new Map(baseline.records.map(x=>[id(x),x]));
const prior=new Map(followup.records.map(x=>[id(x),x]));
const seen=new Set();
for(const r of third.records){
 const k=id(r);assert(!seen.has(k));seen.add(k);
 assert.equal(base.get(k)?.category,'unmatched-catalog');
 const old=prior.get(k);
 assert(!old?.reference?.samePowertrain);
 assert(!old?.dealers?.some(d=>d.listPriceClp>0));
 assert.match(r.reference.url,/^https:\/\//);
 assert(r.reference.commercialVersion);
 assert(r.reference.note);
 if(r.reference.priceClp!==null)assert(Number.isSafeInteger(r.reference.priceClp)&&r.reference.priceClp>0);
 if(r.reference.availability==='anunciado-proximamente')assert.match(r.reference.note,/venta|stock|Próximamente/i);
}
const selected=(model)=>third.records.filter(x=>C.norm(x.model)===C.norm(model));
assert.equal(selected('KYC Gran Mamut 2.0 Cargo Box')[0].reference.availability,'anunciado-proximamente');
assert.equal(selected('Sinotruk Bolden Pro 2.0 AT 4x4')[0].reference.priceClp,26190000);
assert.equal(selected('Sinotruk Bolden Advance 2.0 MT RWD')[0].reference.priceClp,16990000);
assert.equal(selected('Foton View Grand 12').length,2);
assert.equal(selected('Renault Master Furgón L2H2')[0].reference.priceClp,37473100);
assert.equal(selected('Mercedes-Benz CLE 300 4matic Coupé')[0].reference.priceClp,72900000);
assert.equal(selected('Mercedes-Benz CLE 300 4MATIC Cabriolet')[0].reference.priceClp,null);
