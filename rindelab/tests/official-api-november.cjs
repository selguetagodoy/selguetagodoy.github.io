'use strict';
const assert=require('node:assert/strict');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const rd=p=>require(path.join(root,p));
const manifest=rd('vehiculos/data/manifest.json');
const legacy=manifest.files.flatMap(f=>rd('vehiculos/'+f)).filter(r=>r&&r[0]&&r[1]&&r[8]&&r[8]<=manifest.published);
const old=[1,2,3,4].map(i=>rd('rindelab/data/oficial-api-20261018-'+String(i).padStart(2,'0')+'.json'));
const mapper=rd('rindelab/sii/official-api-mapper.js');
const previous=mapper.load(old,legacy);
const snap=rd('rindelab/data/oficial-api-20261122.json');
const added=mapper.loadIncremental(snap,legacy,previous);
assert.equal(legacy.length,8053);
assert.equal(previous.length,272);
assert.equal(added.length,69);
assert.equal(new Set([...legacy,...previous,...added].map(r=>r[9])).size,8394);
assert.equal(added.filter(r=>r[8].startsWith('2026-10')).length,33);
assert.equal(added.filter(r=>r[8].startsWith('2026-11')).length,36);
assert(added.every(r=>r.length===26&&r[11]==='WLTP'));
assert(added.filter(r=>r[2]==='EV').every(r=>r[12]===null&&r[13]>0));
assert(added.filter(r=>r[2]!=='EV').every(r=>r[12]>0));
assert.equal(added.find(r=>r[9]==='KI10713EL1026S00-3')?.[2],'EV');
assert.equal(added.find(r=>r[9]==='CN10615E60826M00-0')?.[2],'REEV');
assert.throws(()=>mapper.loadIncremental({...snap,items:[...snap.items.slice(0,68),snap.items[0]]},legacy,previous),/inválido/);
console.log('PASS: 69 homologaciones adicionales WLTP; 8.394 fichas únicas; base anterior intacta.');
